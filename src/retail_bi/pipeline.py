"""End-to-end build: download -> clean -> star schema -> SQL KPIs -> figures.

Usage:
    python -m retail_bi.pipeline            # full build
    python -m retail_bi.pipeline --refresh  # re-read the Excel file instead of the cache
    python -m retail_bi.pipeline --no-figures
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time

from . import clean, config, extract, figures, kpis, model

log = logging.getLogger("retail_bi")


def reconcile(raw_value: float, rule_log) -> float:
    """Kept value + removed value must equal raw value. Returns the difference."""
    kept = rule_log.loc[rule_log["action"] == "keep", "line_value"].sum()
    removed = rule_log.loc[rule_log["action"] == "remove", "line_value"].sum()
    return float(raw_value - (kept + removed))


def write_quality_report(rule_log, counts: dict[str, int], diff: float) -> None:
    config.REPORT_DIR.mkdir(parents=True, exist_ok=True)
    rule_log.to_csv(config.REPORT_DIR / "data_quality_log.csv", index=False)
    lines = [
        "# Data quality report",
        "",
        "Generated by `python -m retail_bi.pipeline`. Line value = quantity × unit price, in GBP.",
        "",
        "| Rule | Action | Rows | Line value (£) | Meaning |",
        "|---|---|---:|---:|---|",
    ]
    for r in rule_log.itertuples():
        lines.append(f"| `{r.rule}` | {r.action} | {r.rows:,} | {r.line_value:,.2f} | {r.description} |")
    lines += [
        "",
        f"**Reconciliation:** raw line value − (kept + removed) = £{diff:,.2f} (must be 0).",
        "",
        "## Tables loaded",
        "",
        "| Table | Rows |",
        "|---|---:|",
    ]
    lines += [f"| `{name}` | {n:,} |" for name, n in counts.items()]
    (config.REPORT_DIR / "DATA_QUALITY.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def run(refresh: bool = False, make_figures: bool = True) -> dict:
    started = time.perf_counter()
    raw = extract.load_raw(refresh=refresh)
    raw_value = float((raw["quantity"] * raw["unit_price"]).sum())

    lines, rule_log = clean.clean(raw)
    diff = reconcile(raw_value, rule_log)
    if abs(diff) > 0.01:
        raise RuntimeError(f"reconciliation failed: £{diff:,.2f} unaccounted for")
    config.PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    lines.to_parquet(config.CLEAN_PARQUET, index=False)

    counts = model.write_database(lines, rule_log)
    model.write_exports()
    write_quality_report(rule_log, counts, diff)

    results = kpis.run_all()
    if make_figures:
        figures.build_all(results, rule_log)

    summary = results["01_kpi_summary"].iloc[0].to_dict()
    summary["build_seconds"] = round(time.perf_counter() - started, 1)
    (config.REPORT_DIR / "kpi_summary.json").write_text(json.dumps(summary, indent=2, default=str), encoding="utf-8")
    log.info("done in %.1fs", summary["build_seconds"])
    return summary


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--refresh", action="store_true", help="re-read the source Excel file")
    parser.add_argument("--no-figures", action="store_true", help="skip PNG figure generation")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
        stream=sys.stdout,
    )
    summary = run(refresh=args.refresh, make_figures=not args.no_figures)
    print(json.dumps(summary, indent=2, default=str))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
